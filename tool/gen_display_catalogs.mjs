function relativeTimeLocale(language) {
  const tag = info[language].tag;
  const plural = new Intl.PluralRules(tag);
  const number = new Intl.RelativeTimeFormat(tag, { numeric: 'always' });
  const auto = new Intl.RelativeTimeFormat(tag, { numeric: 'auto' });
  const cjkSpacing = value => language.startsWith('zh-')
    ? value.replace(/(\{number\})(?=\p{Script=Han})/gu, '$1 ')
      .replace(/(\p{Script=Han})(?=\{number\})/gu, '$1 ')
    : value;
  const pattern = (count, unit) => {
    const parts = number.formatToParts(count, unit);
    const firstNumber = parts.findIndex(part => part.unit);
    return cjkSpacing(parts.map((part, index) =>
      index === firstNumber ? '{number}' : part.unit ? '' : part.value).join(''));
  };
  const examples = new Map();
  for (const value of [...Array.from({ length: 101 }, (_, index) => index), 1000000]) {
    examples.set(plural.select(value), examples.get(plural.select(value)) ?? value);
  }
  return ['minute', 'hour', 'day'].map(unit => {
    const words = [];
    for (const count of [-2, -1, 0, 1, 2]) {
      const parts = auto.formatToParts(count, unit);
      if (parts.every(part => !part.unit)) {
        words.push(`${count}: ${dartString(parts.map(part => part.value).join(''))}`);
      }
    }
    const patterns = direction => {
      const other = pattern(direction * (examples.get('other') ?? 4), unit);
      const entries = [['other', other]];
      for (const [category, count] of examples) {
        if (category === 'other') continue;
        const text = pattern(direction * count, unit);
        if (text !== other) entries.push([category, text]);
      }
      return `{${entries.map(([category, text]) => `${dartString(category)}: ${dartString(text)}`).join(', ')}}`;
    };
    return `    ({${words.join(', ')}}, ${patterns(-1)}, ${patterns(1)}),`;
  }).join('\n');
}

