// Day periods ICU does not agree with itself about across versions, pinned so
// the generated file is the same on every machine and `--check` means
// something. Korean drifted between ICU 78.2 (AM/PM) and 78.3 (오전/오후) and a
// reviewer on Node 22 got a different file from the one committed on Node 24.
// 오전/오후 is what Korean readers expect, what the current ICU returns and
// what display_language_v124_test asserts.
const dayPeriodOverrides = { ko: { am: '오전', pm: '오후' } };

function datePatterns(language) {
  const tag = info[language].tag;
  const sample = new Date('2026-01-05T06:07:08Z');
  const evening = new Date('2026-01-05T18:07:08Z');
  const clock = { hour: '2-digit', minute: '2-digit' };
  const short = { ...clock, month: 'short', day: 'numeric' };
  const medium = { dateStyle: 'medium', timeStyle: 'short' };
  function pattern(options, hour12) {
    const formatter = new Intl.DateTimeFormat(tag, { ...options, timeZone: 'UTC', hour12 });
    const track = formatter.resolvedOptions().hour12 ? 'h' : 'H';
    return formatter.formatToParts(sample).map(({ type, value }) => {
      switch (type) {
        case 'year': return 'y';
        case 'month': return /^\d+$/.test(value) ? 'M'.repeat(value.length) : 'MMM';
        case 'day': return 'd'.repeat(value.length);
        case 'hour': return track.repeat(value.length);
        case 'minute': return 'mm';
        case 'second': return 'ss';
        case 'dayPeriod': return "'{period}'";
        case 'literal': return `'${value.replaceAll('\u202f', ' ').replaceAll("'", "''")}'`;
        default: throw new Error(`Unsupported date part ${type}`);
      }
    }).join('').replaceAll("''", '');
  }
  const clockFormat = new Intl.DateTimeFormat(tag, { ...clock, timeZone: 'UTC', hour12: true });
  const period = at => clockFormat.formatToParts(at).find(part => part.type === 'dayPeriod')
    .value.replaceAll('\u202f', ' ');
  return [
    ['clock12', pattern(clock, true)],
    ['clockSeconds12', pattern({ ...clock, second: '2-digit' }, true)],
    ['short12', pattern(short, true)],
    ['short24', pattern(short, false)],
    ['medium12', pattern(medium, true)],
    ['medium24', pattern(medium, false)],
    ['am', dayPeriodOverrides[language]?.am ?? period(sample)],
    ['pm', dayPeriodOverrides[language]?.pm ?? period(evening)],
  ];
}

const dates = new Map(newLocales.map(language => [language, datePatterns(language)]));
emit(join(appData, 'display_date_patterns.g.dart'),
  `${header}\ntypedef DisplayDatePatterns = ({\n`
  + dates.get(newLocales[0]).map(([key]) => `  String ${key},`).join('\n')
  + '\n});\n\nconst displayDatePatterns = <String, DisplayDatePatterns>{\n'
  + [...dates].map(([language, entries]) =>
    `  ${dartString(language)}: (\n${entries.map(([key, value]) =>
      `    ${key}: ${dartString(value)},`).join('\n')}\n  ),`).join('\n')
  + '\n};\n');

