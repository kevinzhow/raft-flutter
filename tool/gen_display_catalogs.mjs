const read = path => readFileSync(path, 'utf8');
const evaluate = expression => runInNewContext(`(${expression})`, Object.create(null), { timeout: 1000 });

function exportedValue(path, name, delimiters) {
  const source = read(path);
  const value = source.match(new RegExp(`^export const ${name}\\b[^=]*=\\s*(${delimiters})`, 'm'));
  if (!value) throw new Error(`Cannot find ${name} in ${path}`);
  return evaluate(value[1]);
}

function messages(file, name) {
  const path = join(webCatalog, `${file}.ts`);
  const data = exportedValue(path, name, '\\{[\\s\\S]*?^\\}');
  if (Object.values(data).some(value => typeof value !== 'string')) {
    throw new Error(`Non-string value in ${path}`);
  }
  return data;
}

const displayLocales = join(webSource, 'packages/shared/src/displayLocales.ts');
const order = exportedValue(displayLocales, 'DISPLAY_LOCALES', '\\[[^\\n]*\\]');
const info = exportedValue(displayLocales, 'DISPLAY_LOCALE_INFO', '\\{[\\s\\S]*?^\\}');
const zh = messages('zh-cn', 'zhCn');
const en = { ...messages('enFallback', 'enFallback'), ...messages('en', 'en') };
const jsName = language => language.replace(/-(\w)/g, (_, next) => next.toUpperCase());
const newLocales = order.filter(language => language !== 'en' && language !== 'zh-cn');
const dartString = value => JSON.stringify(value).replaceAll('$', '\\$');
const dartStrings = values => values.map(value => `  ${dartString(value)},`).join('\n');
const sorted = values => [...values].sort();
const string = String.raw`(?:"(?:\\.|[^"\\\r\n])*"|'(?:\\.|[^'\\\r\n])*')`;
const literal = String.raw`(?:${string}\s*)+`;
const decode = value => [...value.matchAll(new RegExp(string, 'g'))]
  .map(match => evaluate(match[0])).join('');
const entries = new RegExp(String.raw`^\s*(${literal}):\s*(${literal}),`, 'gm');
const sources = new Map();
for (const file of sorted(readdirSync(dartCatalog)).filter(name => /^zh_.*(?<!\.g)\.dart$/.test(name))
  .concat('../localization.dart')) {
  for (const [, source, chinese] of read(join(dartCatalog, file)).matchAll(entries)) {
    sources.set(decode(source), decode(chinese));
  }
}
if (sources.size < 1000) throw new Error(`Only found ${sources.size} Dart catalog strings`);

function* dartFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = join(dir, entry.name);
    if (entry.isDirectory()) yield* dartFiles(file);
    else if (/^(?!.*\.g\.dart$).*\.dart$/.test(entry.name)) yield file;
  }
}

const explicitPairs = new Map();
const explicitCall = new RegExp(
  String.raw`\braftTextZh\(\s*[^,\n]+,\s*(${literal}),\s*(${literal})`, 'g',
);
// `raftTextZh` disambiguates by the Simplified Chinese of the intended Web
// key, which only works when the candidates differ there. `Saved` is three Web
// keys that are all 已保存 and yet Сохранённое / Сохранено / Сохранённые in
// Russian, so the call site has to name the Web key itself.
const keyedPairs = new Map();
const keyedCall = new RegExp(
  String.raw`\braftTextKeyed\(\s*[^,\n]+,\s*(${literal}),\s*(${literal})`, 'g',
);
// `raftKeyedLabels` in localization.dart: the same pair, for a label that
// reaches its widget as data instead of through a call. Scoped to that one
// declaration — a bare two-string tuple appears all over the source.
const keyedLabelList = /const raftKeyedLabels = <\(String, String\)>\[([\s\S]*?)\];/;
const keyedLabelEntry = new RegExp(
  String.raw`\(\s*(${literal}),\s*(${literal})\s*\)`, 'g',
);
const hardcodedCall = new RegExp(
  String.raw`\b(?:Text|SelectableText|TextSpan|Semantics|Tooltip|Tab|InputDecoration)\(\s*(?:(?:text|label|message|hintText|labelText):\s*)?(${literal})(?=[,)])`, 'g',
);
const hardcoded = [];
for (const path of ['apps/raft_flutter/lib', 'packages/raft_ui/lib']) {
  for (const file of dartFiles(join(root, path))) {
    const code = read(file);
    for (const [, source, chinese] of code.matchAll(explicitCall)) {
      const pair = [decode(source), decode(chinese)];
      explicitPairs.set(JSON.stringify(pair), pair);
    }
    for (const [, source, key] of code.matchAll(keyedCall)) {
      const pair = [decode(source), decode(key)];
      keyedPairs.set(JSON.stringify(pair), pair);
    }
    const declared = code.match(keyedLabelList);
    if (declared) {
      for (const [, source, key] of declared[1].matchAll(keyedLabelEntry)) {
        const pair = [decode(source), decode(key)];
        keyedPairs.set(JSON.stringify(pair), pair);
      }
    }
    for (const match of code.matchAll(hardcodedCall)) {
      if (/(?<!\\)\$/.test(match[1])) continue;
      const text = decode(match[1]);
      if (!/[A-Za-z]{2}/.test(text)) continue;
      hardcoded.push({
        file: relative(root, file),
        line: code.slice(0, match.index).split('\n').length,
        text,
      });
    }
  }
}

const normalize = text => text.trim().replace(/[’‘]/g, "'")
  .replace(/[“”]/g, '"').replace(/…/g, '...').replace(/\s+/g, ' ')
  .toLowerCase();
const keyIndex = new Map();
for (const [id, source] of Object.entries(en)) {
  if (id.startsWith('fixtures.')) continue;
  const key = normalize(source);
  if (!keyIndex.has(key)) keyIndex.set(key, []);
  keyIndex.get(key).push(id);
}

function webKeys(source, chinese) {
  const candidates = keyIndex.get(normalize(source)) ?? [];
  const exact = candidates.filter(id => en[id] === source);
  const matches = exact.length ? exact : candidates;
  const sameCopy = matches.filter(id => zh[id] === chinese);
  return sameCopy.length ? sameCopy : matches;
}

function syntax(text) {
  const placeholders = [...text.matchAll(/\{(\w+)(?:,\s*(?:plural\s*,|number\s*\})|\})/g)]
    .map(match => match[1]);
  const tags = [...text.matchAll(/<\/?(\w+)>/g)].map(match => match[0]);
  return {
    signature: JSON.stringify([sorted(new Set(placeholders)), sorted(tags)]),
    complex: /[{}]/.test(text.replace(/\{\w+\}/g, '')),
  };
}

function translation(source, chinese, catalog) {
  const keys = webKeys(source, chinese);
  if (!keys.length) return { reason: 'no Web English match' };
  const distinct = new Set(keys.map(id => catalog[id] ?? en[id]));
  // An English collision with different translations needs a call-site hint.
  if (distinct.size !== 1) return { keys, reason: 'ambiguous Web key' };
  const [text] = distinct;
  if (!keys.some(id => Object.hasOwn(catalog, id))) return { keys, reason: 'missing Web translation' };
  const target = syntax(text);
  const supportedIcu = /\{\w+,\s*plural\s*,/.test(source)
    && !/\{\w+,\s*(?:select|selectordinal|date|time)\b|offset:/.test(text);
  if ((target.complex && !supportedIcu) || target.signature !== syntax(source).signature) {
    return { keys, reason: 'unsupported ICU or changed arguments' };
  }
  return { text };
}

const generated = new Map();
const emit = (path, data) => generated.set(path, data);
const fallbackReport = {};
const allFallbacks = new Map();
for (const language of newLocales) {
  const name = jsName(language);
  const catalog = messages(language, name);
  const translated = [];
  const variants = [];
  const fallbacks = [];
  for (const [source, chinese] of [...sources].sort()) {
    const result = translation(source, chinese, catalog);
    if (result.text === undefined) fallbacks.push({ source, ...result });
    else translated.push(`  ${dartString(source)}: ${dartString(result.text)},`);
  }
  for (const [source, chinese] of [...explicitPairs.values()].sort()) {
    const result = translation(source, chinese, catalog);
    if (result.text === undefined) {
      fallbacks.push({ source, chinese, ...result });
    } else {
      variants.push(`  (${dartString(source)}, ${dartString(chinese)}): ${dartString(result.text)},`);
    }
  }
  const keyed = [];
  for (const [source, id] of [...keyedPairs.values()].sort()) {
    if (!Object.hasOwn(en, id)) throw new Error(`raftTextKeyed names no Web id: ${id}`);
    if (normalize(en[id]) !== normalize(source)) {
      throw new Error(`raftTextKeyed ${JSON.stringify(source)} is not ${id} (${JSON.stringify(en[id])})`);
    }
    const text = catalog[id];
    if (text === undefined) {
      fallbacks.push({ source, key: id, reason: 'missing Web translation' });
    } else {
      keyed.push(`  (${dartString(source)}, ${dartString(id)}): ${dartString(text)},`);
    }
  }
  allFallbacks.set(language, fallbacks.filter(row => row.chinese === undefined && row.key === undefined).map(row => row.source));
  fallbackReport[language] = { translated: translated.length, variants: variants.length, fallbacks };
  emit(join(dartCatalog, `display_${language.replace('-', '_')}.g.dart`),
    `${header}\nconst ${name}DisplayCatalog = <String, String>{\n${translated.join('\n')}\n};\n\n`
    + `const ${name}DisplayVariants = <(String, String), String>{\n${variants.join('\n')}\n};\n\n`
    + `const ${name}DisplayKeyed = <(String, String), String>{\n${keyed.join('\n')}\n};\n`);
}

