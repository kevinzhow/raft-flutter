  + `const displayVariants = <String, Map<(String, String), String>>{\n${maps('DisplayVariants')}\n};\n\n`
  + `const displayKeyed = <String, Map<(String, String), String>>{\n${maps('DisplayKeyed')}\n};\n\n`
