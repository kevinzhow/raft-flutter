#!/usr/bin/env python3
"""Generate apps/raft_flutter/test/parity/case_map.g.dart from the case files.

Nothing is registered by hand: every public top-level
`final Map<String, ParityCase> <name> = ...` (or `Map<String, ParityUncovered>`)
in apps/raft_flutter/test/parity/cases/**/*.dart is merged into `parityCases`
(`parityUncovered`). A file that adds a case family only has to declare its map;
no shared file is edited, so parallel branches never touch the same lines.

Names starting with `_` and `*.g.dart` files are ignored. A case id declared by
two maps throws at startup (the old hand-written spreads silently let the last
one win).

The output is git-ignored and regenerated (only rewritten when it changes) by
tool/flutter before any subcommand, by tool/parity and tool/parity-ext/run before
`flutter test`, and by hand:

  python3 tool/parity_case_map.py          # write case_map.g.dart
  python3 tool/parity_case_map.py --list   # print the discovered maps
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PARITY_DIR = ROOT / 'apps/raft_flutter/test/parity'
CASES_DIR = PARITY_DIR / 'cases'
OUTPUT = PARITY_DIR / 'case_map.g.dart'
KINDS = {'ParityCase': 'cases', 'ParityUncovered': 'uncovered'}
_DECL = re.compile(r'^(?:final|const)\s+Map<\s*String\s*,\s*(ParityCase|ParityUncovered)\s*>\s+([A-Za-z][A-Za-z0-9_]*)\s*=',
                   re.M)


def discover(cases_dir=CASES_DIR):
    """-> {'cases': [(relative path, name)], 'uncovered': [...]}, sorted by path then name."""
    cases_dir = pathlib.Path(cases_dir)
    found = {'cases': [], 'uncovered': []}
    for path in sorted(cases_dir.rglob('*.dart')):
        if path.name.endswith('.g.dart'):
            continue
        rel = path.relative_to(cases_dir).as_posix()
        for m in _DECL.finditer(path.read_text()):
            found[KINDS[m.group(1)]].append((rel, m.group(2)))
    for kind in found.values():
        kind.sort()
    return found


def render(found):
    by_file = {}
    for kind in ('cases', 'uncovered'):
        for rel, name in found[kind]:
            by_file.setdefault(rel, []).append(name)
    lines = ['// GENERATED by tool/parity_case_map.py; do not edit (git-ignored, regenerated by tool/flutter).',
             '// Every public top-level Map<String, ParityCase> / Map<String, ParityUncovered> under cases/.',
             "import 'parity_harness.dart';"]
    for rel in sorted(by_file):
        names = ', '.join(sorted(by_file[rel]))
        lines.append(f"import 'cases/{rel}' show {names};")
    lines += ['',
              'Map<String, T> _merge<T>(String what, List<MapEntry<String, Map<String, T>>> parts) {',
              '  final merged = <String, T>{};',
              '  final owner = <String, String>{};',
              '  for (final part in parts) {',
              '    for (final entry in part.value.entries) {',
              '      final previous = owner[entry.key];',
              '      if (previous != null) {',
              "        throw StateError('$what: case id ${entry.key} is declared by both $previous and ${part.key}');",
              '      }',
              '      owner[entry.key] = part.key;',
              '      merged[entry.key] = entry.value;',
              '    }',
              '  }',
              '  return merged;',
              '}']
    for kind, var, typ in (('cases', 'parityCases', 'ParityCase'), ('uncovered', 'parityUncovered', 'ParityUncovered')):
        lines += ['', f'final Map<String, {typ}> {var} = _merge<{typ}>(\'{var}\', [']
        lines += [f"  MapEntry('{name}', {name})," for _, name in found[kind]]
        lines += ['  ]);']
    return '\n'.join(lines) + '\n'


def write(output=OUTPUT, cases_dir=CASES_DIR):
    """Rewrite the generated file when its content changed; -> True if written."""
    text = render(discover(cases_dir))
    output = pathlib.Path(output)
    if output.is_file() and output.read_text() == text:
        return False
    output.write_text(text)
    return True


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--list', action='store_true', help='print the discovered maps instead of writing')
    args = ap.parse_args(argv)
    if args.list:
        for kind, items in discover().items():
            print(f'{kind}:')
            for rel, name in items:
                print(f'  {name}  ({rel})')
        return 0
    write()
    return 0


if __name__ == '__main__':
    sys.exit(main())
