#!/usr/bin/env node
// Snapshot the Web client's top-level `@theme` blocks (packages/web/src/index.css)
// into tool/recipes/web-theme.css. The Web compiles raft-ui recipes with these
// overrides (e.g. --color-brutal-yellow: #FFD440), so the recipe resolver
// layers them after raft-ui styles.css to match what the Web renders.
//
// Usage: node tool/recipes/sync-web-theme.mjs [path/to/web/src/index.css]
// Without an argument uses $RAFT_WEB_CSS; exits quietly if the file is absent
// (the committed snapshot is then used as-is).
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ?? process.env.RAFT_WEB_CSS;
if (!src || !existsSync(src)) {
  console.log('sync-web-theme: Web index.css not available; keeping committed snapshot');
  process.exit(0);
}
const css = readFileSync(src, 'utf8');
const blocks = [];
postcss.parse(css).each((node) => {
  if (node.type === 'atrule' && node.name === 'theme') blocks.push(node.toString());
});
const out = [
  '/* GENERATED by tool/recipes/sync-web-theme.mjs — do not edit.',
  ' * Top-level @theme blocks of the Raft Web client (packages/web/src/index.css,',
  ` * sha256 ${createHash('sha256').update(css).digest('hex')}).`,
  ' * Layered after raft-ui styles.css when compiling recipe classes. */',
  '',
  ...blocks,
  '',
].join('\n');
writeFileSync(join(here, 'web-theme.css'), out);
console.log(`sync-web-theme: ${blocks.length} @theme block(s) from ${src}`);
