// Generates the raft_ui recipe router: packages/raft_ui/lib/src/recipes/*.g.dart.
//
// Two generated recipe sets exist in raft_theme:
//   lib/recipes/*.g.dart         the Raft set (current raft-ui, no `theme` axis),
//                                produced by gen_dart.mjs.
//   lib/recipes/legacy/*.g.dart  the frozen raft-ui 0.5.52 set of the Elegant and
//                                Brutal looks (see lib/recipes_legacy.dart); never
//                                regenerated, never edited.
//
// Components keep calling `RaftXRecipe.resolve(theme: ..., tokens: ...)`. The class
// they reach is generated here, one per recipe, with the legacy signature. It
// forwards to the legacy class unchanged when the resolver says `legacy` (so
// Elegant and Brutal are byte-identical by construction), and to the Raft class
// otherwise, mapping axis values by their CSS name and slots by name. A legacy
// slot or axis value the Raft recipe no longer has resolves to an empty slot or
// the axis default; Raft-only slots and axes are reachable through
// `package:raft_theme/recipes.dart`. The set is chosen in one place:
// `RaftThemePackRecipes.recipeSet` -> `RaftTokens.recipeSet` ->
// `RaftRecipeTokens.recipeSet`.
//
// Usage: node tool/recipes/gen_router.mjs [--check]
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { homedir, tmpdir } from 'node:os';

const repo = join(dirname(fileURLToPath(import.meta.url)), '../..');
const raftDir = join(repo, 'packages/raft_theme/lib/recipes');
const legacyDir = join(raftDir, 'legacy');
const outDir = join(repo, 'packages/raft_ui/lib/src/recipes');
const check = process.argv.includes('--check');

const skip = new Set(['recipes.g.dart', 'recipe_utilities.g.dart']);
const recipeFiles = (dir) =>
  readdirSync(dir).filter((f) => f.endsWith('.g.dart') && !skip.has(f)).sort();

function parseParams(block) {
  return block
    .split('\n')
    .map((l) => l.trim().replace(/,$/, ''))
    .filter(Boolean)
    .map((l) => {
      const m = l.match(/^(required )?(\S+?)\s+(\w+)(?: = (.+))?$/);
      if (!m) throw new Error(`cannot parse parameter "${l}"`);
      return { required: !!m[1], type: m[2], name: m[3], dflt: m[4] ?? null, line: l };
    });
}

function parse(path) {
  const text = readFileSync(path, 'utf8');
  const cls = text.match(/abstract final class (\w+) \{/)?.[1];
  if (!cls) throw new Error(`${path}: no recipe class`);
  const sig = text.match(new RegExp(`static ${cls}Style resolve\\(\\{\\n([\\s\\S]*?)\\n  \\}\\) \\{`));
  if (!sig) throw new Error(`${path}: no resolve()`);
  const styleBlock = text.match(new RegExp(`class ${cls}Style \\{([\\s\\S]*?)\\n\\}`))[1];
  const slots = [...styleBlock.matchAll(/final RaftSlotStyle (\w+);/g)].map((m) => m[1]);
  return { cls, params: parseParams(sig[1]), slots };
}

const header = (file) =>
  `// GENERATED by tool/recipes/gen_router.mjs from raft_theme's recipes/${file} and\n` +
  `// recipes/legacy/${file} — do not edit. Regenerate with \`tool/recipes/run\`.\n` +
  `// ignore_for_file: type=lint\n`;

function facade(file) {
  const L = parse(join(legacyDir, file));
  const R = parse(join(raftDir, file));
  if (L.cls !== R.cls) throw new Error(`${file}: class ${L.cls} vs ${R.cls}`);
  const cls = L.cls;
  const rParam = new Map(R.params.map((p) => [p.name, p]));
  const fwd = [];
  const raftArgs = [];
  const notes = [];
  for (const p of L.params) {
    if (p.name === 'states' || p.name === 'tokens') continue;
    fwd.push(`${p.name}: ${p.name}`);
    if (p.name === 'theme') continue;
    const rp = rParam.get(p.name);
    if (!rp) {
      notes.push(`legacy-only axis \`${p.name}\``);
      continue;
    }
    const enumLike = (t) => /^Raft\w+Recipe\w+\??$/.test(t);
    if (p.type === 'bool?' && rp.type === 'bool?') {
      raftArgs.push(`${p.name}: ${p.name}`);
    } else if (enumLike(p.type) && enumLike(rp.type)) {
      const rt = rp.type.replace(/\?$/, '');
      raftArgs.push(`${p.name}: routeAxis(${p.name}?.css, raft.${rt}.values, (e) => e.css)`);
    } else {
      notes.push(`axis \`${p.name}\` has different kinds (${p.type} / ${rp.type})`);
    }
  }
  for (const p of R.params) {
    if (['states', 'tokens'].includes(p.name)) continue;
    if (!L.params.some((q) => q.name === p.name)) notes.push(`Raft-only axis \`${p.name}\``);
  }
  const rSlots = new Set(R.slots);
  const dropped = L.slots.filter((s) => !rSlots.has(s));
  const added = R.slots.filter((s) => !L.slots.includes(s));
  if (dropped.length) notes.push(`legacy slots empty in the Raft set: ${dropped.join(', ')}`);
  if (added.length) notes.push(`Raft-only slots: ${added.join(', ')}`);
  const slotArgs = L.slots
    .map((s) => `      ${s}: ${rSlots.has(s) ? `s.${s}` : 'absentSlot(tokens)'},`)
    .join('\n');
  const params = L.params.map((p) => `    ${p.line},`).join('\n');
  const legacyCall = [...fwd, 'states: states', 'tokens: tokens'].map((a) => `        ${a},`).join('\n');
  const raftCall = [...raftArgs, 'states: states', 'tokens: tokens'].map((a) => `        ${a},`).join('\n');
  const doc = notes.length ? `\n///\n/// Raft set differences: ${notes.join('; ')}.` : '';
  return {
    notes,
    text: `${header(file)}
import 'package:raft_theme/recipes/recipe_runtime.dart';
import 'package:raft_theme/recipes/${file}' as raft;
import 'package:raft_theme/recipes/legacy/${file}' as legacy;
import 'package:raft_theme/recipes/legacy/${file}' hide ${cls};

import 'recipe_router.dart';

export 'package:raft_theme/recipes/legacy/${file}' hide ${cls};

/// Router for recipe \`${cls}\`: the frozen 0.5.52 class for the Elegant and Brutal
/// looks, the current raft-ui class for the Raft look.${doc}
abstract final class ${cls} {
  static const String recipeName = legacy.${cls}.recipeName;
  static const List<String> slotNames = legacy.${cls}.slotNames;
  static const List<RaftRecipeAxis> axes = legacy.${cls}.axes;

  static ${cls}Style resolve({
${params}
  }) {
    if (usesLegacyRecipes(tokens)) {
      return legacy.${cls}.resolve(
${legacyCall}
      );
    }
    final s = raft.${cls}.resolve(
${raftCall}
    );
    return ${cls}Style(
${slotArgs}
    );
  }

  /// Resolve by raw tailwind-variants props; for tooling and tests.
  static Map<String, RaftSlotStyle> resolveProps(
    Map<String, String?> props, {
    RaftRecipeStates states = RaftRecipeStates.none,
    RaftTokenResolver? tokens,
  }) {
    if (usesLegacyRecipes(tokens)) {
      return legacy.${cls}.resolveProps(props, states: states, tokens: tokens);
    }
    return withLegacySlots(
      raft.${cls}.resolveProps(props, states: states, tokens: tokens),
      slotNames,
      tokens,
    );
  }
}
`,
  };
}

const legacyFiles = new Set(recipeFiles(legacyDir));
const raftFiles = new Set(recipeFiles(raftDir));
const out = new Map();
const report = [];
const barrel = [];
for (const f of [...new Set([...legacyFiles, ...raftFiles])].sort()) {
  if (legacyFiles.has(f) && raftFiles.has(f)) {
    const r = facade(f);
    out.set(f, r.text);
    if (r.notes.length) report.push(`${f}: ${r.notes.join('; ')}`);
  } else if (raftFiles.has(f)) {
    out.set(f, `// Raft-only recipe; the router has nothing to choose.\nexport 'package:raft_theme/recipes/${f}';\n`);
    report.push(`${f}: Raft-only recipe (no legacy equivalent)`);
  } else {
    out.set(f, `// Removed from raft-ui after 0.5.52; only the frozen looks have it.\nexport 'package:raft_theme/recipes/legacy/${f}';\n`);
    report.push(`${f}: legacy-only recipe (removed upstream)`);
  }
  barrel.push(`export '${f}';`);
}
out.set(
  'recipes.g.dart',
  `// GENERATED by tool/recipes/gen_router.mjs — do not edit. Barrel of the recipe router.\n\n${barrel.join('\n')}\n`,
);

// Same pinned formatter and language version as gen_dart.mjs.
const flutterVersion = JSON.parse(readFileSync(join(repo, '.fvmrc'), 'utf8')).flutter;
const dartName = process.platform === 'win32' ? 'dart.exe' : 'dart';
const dart = process.env.RAFT_DART_BIN ?? [
  join(repo, '.fvm/flutter_sdk/bin', dartName),
  join(homedir(), 'flutter-sdks/versions', flutterVersion, 'bin', dartName),
  join(homedir(), 'fvm/versions', flutterVersion, 'bin', dartName),
].find(existsSync);
if (!dart) throw new Error(`Install the pinned Flutter ${flutterVersion} to format router outputs`);
const languageVersion = /^environment:\s*\n\s+sdk:\s*['"]?\^?(\d+\.\d+)/m.exec(
  readFileSync(join(repo, 'pubspec.yaml'), 'utf8'),
)?.[1];

function emit(dir) {
  mkdirSync(dir, { recursive: true });
  for (const [f, text] of out) writeFileSync(join(dir, f), text);
  execFileSync(dart, ['format', `--language-version=${languageVersion}`, dir], { cwd: repo, stdio: 'pipe' });
}

if (check) {
  const tmp = mkdtempSync(join(tmpdir(), 'router-'));
  try {
    emit(tmp);
    let stale = 0;
    for (const f of out.keys()) {
      const p = join(outDir, f);
      if (!existsSync(p) || !readFileSync(p).equals(readFileSync(join(tmp, f)))) { stale++; console.error(`stale: ${f}`); }
    }
    for (const f of readdirSync(outDir)) {
      if (f.endsWith('.g.dart') && !out.has(f)) { stale++; console.error(`orphan: ${f}`); }
    }
    process.exit(stale ? 1 : 0);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
emit(outDir);
for (const f of readdirSync(outDir)) {
  if (f.endsWith('.g.dart') && !out.has(f)) rmSync(join(outDir, f));
}
mkdirSync(join(repo, 'build/recipes'), { recursive: true });
writeFileSync(join(repo, 'build/recipes/router-report.txt'), report.join('\n') + '\n');
console.log(`router: ${out.size - 1} recipe files, ${report.length} with set differences`);
