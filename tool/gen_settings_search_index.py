#!/usr/bin/env python3
"""Generate apps/raft_flutter/lib/features/settings_search_index.dart.

The settings the Web's Settings search finds: packages/shared/src/settingsSearch.v1.json (where a
setting is and the other words for it) plus the Web's own words for each, looked up by message id
in the Web's en.ts (SETTINGS_SEARCH_COPY in features/settings/search/settingsSearchCopy.ts names the
ids). The app has two display languages, so only the `en` and `zh-cn` aliases are kept; the zh words
of names, descriptions and sections come from the zh catalog files (English text is the key).

  python3 tool/gen_settings_search_index.py --web-src <raft source root> [--check]
  python3 tool/gen_settings_search_index.py --zh        # print the zh catalog lines for strings the catalog lacks
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'apps/raft_flutter/lib/features/settings_search_index.dart'
DEFAULT_SRC = pathlib.Path('/mnt/data/tmp/cindy/upstream-24/src-124')

# The Web's entries this app does not list: the desktop app card is for browsers only, and this app is
# the desktop app (useSettingsSearchSettings `desktop-app: !desktopApp`).
SKIPPED = {'desktop-app'}

_PAIR = re.compile(r'^\s*"([\w.\-]+)":\s*("(?:[^"\\]|\\.)*")\s*,?\s*$', re.M)
_PAIR_NEXT = re.compile(r'^\s*"([\w.\-]+)":\s*\n\s*("(?:[^"\\]|\\.)*")\s*,?\s*$', re.M)
_COPY = re.compile(
    r'^\s*(?:"([\w\-]+)"|([\w]+)):\s*\{\s*nameId:\s*"([\w.]+)"'
    r'(?:,\s*descriptionId:\s*"([\w.]+)")?(?:,\s*sectionId:\s*"([\w.]+)")?\s*\},?\s*$',
    re.M,
)


def catalog(path):
    text = path.read_text(encoding='utf8')
    out = {}
    for pattern in (_PAIR, _PAIR_NEXT):
        for m in pattern.finditer(text):
            out[m.group(1)] = json.loads(m.group(2))
    return out


def dart(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def dart_list(words):
    return '[' + ', '.join(dart(w) for w in words) + ']'


def build(src):
    web = src / 'packages/web/src'
    index = json.loads((src / 'packages/shared/src/settingsSearch.v1.json').read_text(encoding='utf8'))
    en = catalog(web / 'i18n/messages/en.ts')
    copy = {}
    for m in _COPY.finditer((web / 'features/settings/search/settingsSearchCopy.ts').read_text(encoding='utf8')):
        copy[m.group(1) or m.group(2)] = (m.group(3), m.group(4), m.group(5))
    rows, strings = [], set()
    for entry in index['entries']:
        if entry.get('experimental') or entry['id'] in SKIPPED:
            continue
        name_id, description_id, section_id = copy[entry['id']]
        name, description, section = en[name_id], en.get(description_id) if description_id else None, \
            en.get(section_id) if section_id else None
        strings.update(s for s in (name, description, section) if s)
        aliases = entry['aliases']
        rows.append(
            f"  SettingsSearchEntry(\n"
            f"    id: {dart(entry['id'])},\n"
            f"    page: {dart(entry['page'])},\n"
            f"    name: {dart(name)},\n"
            + (f"    description: {dart(description)},\n" if description else '')
            + (f"    section: {dart(section)},\n" if section else '')
            + f"    aliases: {dart_list(aliases['en'])},\n"
            + (f"    aliasesZh: {dart_list(aliases['zh-cn'])},\n" if aliases.get('zh-cn') else '')
            + "  ),\n"
        )
    header = (
        "// GENERATED by tool/gen_settings_search_index.py from Web v1.24.0's\n"
        "// packages/shared/src/settingsSearch.v1.json and its en.ts words; do not edit.\n"
        "// Rows the app does not list: desktop-app (the app is the desktop app).\n"
        "import 'settings_search_match.dart' show SettingsSearchEntry;\n\n"
        "/// The settings Settings search finds, in the Web's list order. Names, descriptions and sections are\n"
        "/// English source text (the catalog is keyed by it); `{serverName}` is filled by the caller.\n"
        "const settingsSearchIndex = <SettingsSearchEntry>[\n"
    )
    return header + ''.join(rows) + '];\n', strings


def zh_missing(src, strings):
    web = src / 'packages/web/src'
    en, zh = catalog(web / 'i18n/messages/en.ts'), catalog(web / 'i18n/messages/zh-cn.ts')
    by_en = {v: zh[k] for k, v in en.items() if k in zh}
    existing = ''
    for path in sorted((ROOT / 'packages/raft_ui/lib/src/l10n').glob('zh_*.dart')):
        if not path.name.endswith('.g.dart'):
            existing += path.read_text(encoding='utf8')
    for text in sorted(strings):
        if text in by_en and dart(text) not in existing and json.dumps(text, ensure_ascii=False) not in existing:
            print(f'  {json.dumps(text, ensure_ascii=False)}: {json.dumps(by_en[text], ensure_ascii=False)},')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--web-src', type=pathlib.Path, default=DEFAULT_SRC)
    ap.add_argument('--check', action='store_true', help='fail when the committed file differs')
    ap.add_argument('--zh', action='store_true', help='print zh catalog lines the catalog files lack')
    args = ap.parse_args(argv)
    text, strings = build(args.web_src)
    if args.zh:
        zh_missing(args.web_src, strings)
        return 0
    if args.check:
        return 0 if OUTPUT.read_text() == text else 1
    OUTPUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
