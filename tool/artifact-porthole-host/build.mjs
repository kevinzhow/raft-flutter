#!/usr/bin/env node
// Bundles host_entry.mjs with @botiverse/porthole from a Raft Web v1.24.0 checkout that has its
// dependencies installed. Usage: node build.mjs <raft-source checkout> <output.js>
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const [source, output] = process.argv.slice(2);
if (!source || !output) {
  console.error("Usage: node build.mjs <raft-source checkout> <output.js>");
  process.exit(2);
}
const here = dirname(fileURLToPath(import.meta.url));
const web = join(resolve(source), "packages/web");
const require = createRequire(join(web, "package.json"));
const esbuild = require(require.resolve("esbuild", { paths: [join(resolve(source), "packages/content-worker"), web] }));
const result = await esbuild.build({
  entryPoints: [join(here, "host_entry.mjs")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["chrome111", "safari16"],
  minify: true,
  legalComments: "eof",
  banner: { js: "/*! WP-ART0 Artifact frame host. Bundles @botiverse/porthole 0.16.0, Apache-2.0, copyright Botiverse (docs/licenses/porthole-0.16.0-Apache-2.0.txt). Generated by tool/artifact-porthole-host/build.mjs: do not edit. */" },
  nodePaths: [join(web, "node_modules")],
  alias: { "raft-shared/artifactPageTheme": join(resolve(source), "packages/shared/src/artifactPageTheme.ts") },
  outfile: resolve(output),
  metafile: true,
});
const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`wrote ${output} (${bytes} bytes)`);
