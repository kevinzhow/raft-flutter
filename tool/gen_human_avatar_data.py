#!/usr/bin/env python3
"""Regenerate packages/raft_ui/lib/src/human_avatar_data.dart from Web's shared
humanAvatarLayers.json (the human pixel-avatar art, shared/assets).

usage: tool/gen_human_avatar_data.py <humanAvatarLayers.json>

The art is 18 layers of 112x112 role grids (~225 KB as text). Each row is
run-length encoded as <ROLE><count> pairs, the role as the uppercase letter
`A` + role index (role chars are 0-9 then a-z, so 0 -> A, 1 -> B, ... c -> M):
digits stay unambiguous in the counts. Rows are joined with `/`. The Dart
decoder is RaftHumanAvatarLayer.rows in human_avatar_layer.dart.
Rerun after a raft-ui/shared art bump; the file is written whole.
"""
import json
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parents[1] / "packages/raft_ui/lib/src/human_avatar_data.dart"


def role_letter(ch):
    return chr(ord("A") + int(ch, 36))


def encode_row(row):
    out, i = [], 0
    while i < len(row):
        j = i
        while j < len(row) and row[j] == row[i]:
            j += 1
        out.append(f"{role_letter(row[i])}{j - i}")
        i = j
    return "".join(out)


def q(s):
    assert "'" not in s and "\\" not in s and "$" not in s
    return f"'{s}'"


def main():
    d = json.load(open(sys.argv[1]))
    size = d["size"]
    o = [
        "// GENERATED by tool/gen_human_avatar_data.py from packages/shared/assets/humanAvatarLayers.json.",
        "// Do not edit: rerun `tool/gen_human_avatar_data.py <humanAvatarLayers.json>`.",
        f"// Human pixel-avatar art (avatar-layers v{d['version']}), artVersion {d['artVersion']}.",
        "// ignore_for_file: lines_longer_than_80_chars",
        "import 'human_avatar_layer.dart';",
        "",
        f"const raftHumanAvatarArtVersion = {q(str(d['artVersion']))};",
        f"const raftHumanAvatarSize = {size};",
        "",
        "/// Role character -> `fixed:<key>` or `palette:<skin|hair>`; role 0 is transparent.",
        "const raftHumanAvatarRoleColors = <String, String>{",
    ]
    for k, v in d["roleColors"].items():
        o.append(f"  {q(k)}: {q(v)},")
    o += ["};", "", "const raftHumanAvatarFixedColors = <String, String>{"]
    for k, v in d["fixed"].items():
        o.append(f"  {q(k)}: {q(v)},")
    o.append("};")
    for name in ("background", "skin", "hair"):
        o += ["", f"const raftHumanAvatar{name.capitalize()}Palette = <String, String>{{"]
        for k, v in d["palettes"][name].items():
            o.append(f"  {q(k)}: {q(v)},")
        o.append("};")
    o += ["", "const raftHumanAvatarLayers = <RaftHumanAvatarLayer>["]
    for l in d["layers"]:
        assert len(l["rows"]) == size and all(len(r) == size for r in l["rows"])
        runs = "/".join(encode_row(r) for r in l["rows"])
        # The shape `dart format` gives a constructor call too long for a line.
        o += [
            "  RaftHumanAvatarLayer(",
            f"    {q(l['layer'])},",
            f"    {q(l['option'])},",
            f"    {l.get('z') or 0},",
            f"    {q(runs)},",
            "  ),",
        ]
    o.append("];")
    OUT.write_text("\n".join(o) + "\n")


main()
