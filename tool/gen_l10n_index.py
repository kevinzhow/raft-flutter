#!/usr/bin/env python3
"""Generate packages/raft_ui/lib/src/l10n/zh_index.g.dart from the zh catalog files.

Every packages/raft_ui/lib/src/l10n/zh_*.dart declares public top-level
`const Map<String, String> zhCatalog<Name> = ...` (English source text -> Chinese).
The generated index merges them into `zhCatalogAll` (used by `raftChinese` in
localization.dart) and lists them in `zhCatalogParts` for the duplicate-key test
(packages/raft_ui/test/zh_catalog_files_test.dart). Adding a feature's strings is
adding one file; no shared file is edited.

The output is git-ignored and regenerated (only rewritten when it changes) by
tool/flutter before every subcommand, and by hand:

  python3 tool/gen_l10n_index.py          # write zh_index.g.dart
  python3 tool/gen_l10n_index.py --list   # print the discovered catalogs
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
L10N_DIR = ROOT / 'packages/raft_ui/lib/src/l10n'
OUTPUT = L10N_DIR / 'zh_index.g.dart'
_DECL = re.compile(r'^const\s+Map<\s*String\s*,\s*String\s*>\s+(zhCatalog[A-Za-z0-9]*)\s*=', re.M)


def discover(l10n_dir=L10N_DIR):
    """-> sorted [(file name, map name)] of every zh_*.dart catalog (not the generated index)."""
    found = []
    for path in sorted(pathlib.Path(l10n_dir).glob('zh_*.dart')):
        if path.name.endswith('.g.dart'):
            continue
        names = _DECL.findall(path.read_text())
        if not names:
            raise SystemExit(f'{path}: no `const Map<String, String> zhCatalog<Name> = ...` declaration')
        found += [(path.name, n) for n in names]
    return sorted(found)


def render(found):
    lines = ['// GENERATED by tool/gen_l10n_index.py; do not edit (git-ignored, regenerated by tool/flutter).',
             '// Merges every zh_*.dart catalog in this directory.']
    for file, name in found:
        lines.append(f"import '{file}' show {name};")
    lines += ['', '/// Each catalog by name, for the duplicate-key test.',
              'const zhCatalogParts = <String, Map<String, String>>{']
    lines += [f"  '{name}': {name}," for _, name in found]
    lines += ['};', '', '/// Every zh catalog merged (a key must live in exactly one catalog).',
              'const zhCatalogAll = <String, String>{']
    lines += [f'  ...{name},' for _, name in found]
    lines += ['};']
    return '\n'.join(lines) + '\n'


def write(output=OUTPUT, l10n_dir=L10N_DIR):
    """Rewrite the generated file when its content changed; -> True if written."""
    if not pathlib.Path(l10n_dir).is_dir():
        return False
    text = render(discover(l10n_dir))
    output = pathlib.Path(output)
    if output.is_file() and output.read_text() == text:
        return False
    output.write_text(text)
    return True


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--list', action='store_true')
    args = ap.parse_args(argv)
    if args.list:
        for file, name in discover():
            print(f'{name}  ({file})')
        return 0
    write()
    return 0


if __name__ == '__main__':
    sys.exit(main())
