#!/usr/bin/env node
// Generates lib/features/agent_runtime_catalog.dart from the pinned Raft source
// (packages/shared/src): the runtime model catalogs with their reasoning
// metadata, the reasoning effort ladder and the runtime capability sets the
// legacy runtime config editor reads (Web `RuntimeConfigFields` +
// `reasoningEffortOptions`). Built-in Pi / Pi / Kimi Code keep provider
// machinery of their own and are not part of this catalog.
//
//   RAFT_SOURCE=<raft-source checkout> node tool/gen_runtime_catalog.mjs
//
// The source checkout is only read (esbuild bundles packages/shared/src/index.ts
// into a temp file).
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = process.env.RAFT_SOURCE;
if (!root) throw new Error("set RAFT_SOURCE to the raft-source checkout");
const pnpm = join(root, "node_modules/.pnpm");
const esbuildDir = readdirSync(pnpm).filter((d) => d.startsWith("esbuild@")).sort().at(-1);
const esbuild = join(pnpm, esbuildDir, "node_modules/esbuild/bin/esbuild");
const out = join(mkdtempSync(join(tmpdir(), "raft-shared-")), "shared.cjs");
execFileSync(esbuild, [join(root, "packages/shared/src/index.ts"), "--bundle", "--platform=node", "--format=cjs", `--outfile=${out}`, "--log-level=error"]);
const s = createRequire(import.meta.url)(out);

const SKIP = new Set(["builtin", "pi", "kimi-sdk", "external"]);
const dq = (v) => JSON.stringify(v).replace(/\$/g, "\\$");
const model = (m, verified) => {
  const parts = [`id: ${dq(m.id)}`, `label: ${dq(m.label)}`];
  if (m.supportedReasoningEfforts) parts.push(`supportedReasoningEfforts: [${m.supportedReasoningEfforts.map(dq).join(", ")}]`);
  if (m.defaultReasoningEffort) parts.push(`defaultReasoningEffort: ${dq(m.defaultReasoningEffort)}`);
  if (verified) parts.push(`verified: ${dq(verified)}`);
  return `    RuntimeModelInfo(${parts.join(", ")}),`;
};

let dart = `// GENERATED by tool/gen_runtime_catalog.mjs from the pinned Raft shared package; do not edit.
// ignore_for_file: lines_longer_than_80_chars

/// \`RuntimeModelInfo\` of packages/shared (the fields the editor reads).
class RuntimeModelInfo {
  const RuntimeModelInfo({
    required this.id,
    required this.label,
    this.supportedReasoningEfforts,
    this.defaultReasoningEffort,
    this.verified,
  });
  final String id, label;
  final List<String>? supportedReasoningEfforts;
  final String? defaultReasoningEffort;

  /// \`launchable\` or \`suggestion_only\` (null = not declared).
  final String? verified;
}

/// \`RUNTIME_CONFIG_VERSION\`.
const runtimeConfigVersion = ${s.RUNTIME_CONFIG_VERSION};

/// \`REASONING_EFFORTS\` (id, label) in ladder order.
const reasoningEfforts = <(String, String)>[
${s.REASONING_EFFORTS.map((e) => `  (${dq(e.id)}, ${dq(e.label)}),`).join("\n")}
];

/// \`BASE_REASONING_EFFORTS\`: the set a model that declares none gets.
const baseReasoningEfforts = <String>{${s.BASE_REASONING_EFFORTS.map(dq).join(", ")}};

/// \`REASONING_EFFORT_RUNTIMES\`.
const reasoningEffortRuntimes = <String>{${[...s.REASONING_EFFORT_RUNTIMES].map(dq).join(", ")}};

/// \`RUNTIME_FAST_MODE_RUNTIMES\`.
const fastModeRuntimes = <String>{${[...s.RUNTIME_FAST_MODE_RUNTIMES].map(dq).join(", ")}};

/// \`RUNTIMES\` (id, displayName, binary, supported, deprecated).
const runtimeInfos = <({String id, String name, String binary, bool supported, bool deprecated})>[
${s.RUNTIMES.map((r) => `  (id: ${dq(r.id)}, name: ${dq(r.displayName)}, binary: ${dq(r.binary)}, supported: ${r.supported}, deprecated: ${Boolean(r.deprecated)}),`).join("\n")}
];

/// \`RUNTIME_MODELS\` of the runtimes the legacy editor covers; the first entry
/// is \`getDefaultModel\`.
const runtimeModelCatalog = <String, List<RuntimeModelInfo>>{
`;
for (const [rt, models] of Object.entries(s.RUNTIME_MODELS)) {
  if (SKIP.has(rt)) continue;
  dart += `  ${dq(rt)}: [\n${models.map((m) => model(m)).join("\n")}\n  ],\n`;
}
dart += `};

/// \`getStaticRuntimeModelSourceSet\`: closed static catalogs (with the
/// declared verification applied); other runtimes are discovered on the
/// Computer.
const staticRuntimeModelSources = <String, List<RuntimeModelInfo>>{
`;
for (const rt of Object.keys(s.RUNTIME_MODELS)) {
  if (SKIP.has(rt)) continue;
  const set = s.getStaticRuntimeModelSourceSet(rt);
  if (!set) continue;
  dart += `  ${dq(rt)}: [\n${set.models.map((m) => model(m, m.verified)).join("\n")}\n  ],\n`;
}
dart += `};
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), "../lib/features/agent_runtime_catalog.dart");
writeFileSync(dest, dart);
console.log("wrote", dest);
