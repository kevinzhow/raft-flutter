/// A suggested agent name, never one in [exclude] (names already taken,
/// compared trimmed and case-insensitive): a free first name at random; when
/// none is free, a free `Adjective-Name` pair at random; when none of those is
/// free either, a random pair with the first free number appended.
String suggestAgentName({
  Iterable<String> exclude = const [],
  math.Random? random,
}) {
  final rng = random ?? math.Random();
  final taken = {for (final name in exclude) name.trim().toLowerCase()};
  bool isFree(String name) => !taken.contains(name.toLowerCase());
  String pick(List<String> pool) => pool[rng.nextInt(pool.length)];
  final names = agentClassicNames.where(isFree).toList();
  if (names.isNotEmpty) return pick(names);
  final paired = [
    for (final adjective in agentNameAdjectives)
      for (final name in agentClassicNames) '$adjective-$name',
  ];
  final pairs = paired.where(isFree).toList();
  if (pairs.isNotEmpty) return pick(pairs);
  final base = pick(paired);
  for (var suffix = 2; ; suffix++) {
    if (isFree('$base$suffix')) return '$base$suffix';
  }
}
