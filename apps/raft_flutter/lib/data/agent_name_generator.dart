/// A suggested agent name, `adjective-noun`, picked at random from the pairs
/// not in [exclude] (names already taken, compared trimmed and case-insensitive),
/// so it never collides while any pair is free. Only when every pair is taken
/// does it return a taken one, and the server's uniqueness check decides.
String suggestAgentName({
  Iterable<String> exclude = const [],
  math.Random? random,
}) {
  final taken = {for (final name in exclude) name.trim().toLowerCase()};
  final all = [
    for (final adjective in agentNameAdjectives)
      for (final noun in agentNameNouns) '$adjective-$noun',
  ];
  final free = all.where((name) => !taken.contains(name)).toList();
  final pool = free.isEmpty ? all : free;
  return pool[(random ?? math.Random()).nextInt(pool.length)];
}
