/// Diagram roles stay independent of the application Material color scheme.
class DiagramSemantic {
  const DiagramSemantic({required this.dark});
  final bool dark;
  core.Color color(String role) {
    final css = (dark ? DiagramPrimitive.dark : DiagramPrimitive.light)[role]!;
    final parsed = core.Color.tryParse(css);
    if (parsed != null) return parsed;
    // The actual Web 11.16 base theme emits NaN lightness for this role.
    // SVG discards it and inherits the renderer root foreground fill.
    if (role == 'quadrantPointFill' && css.contains('NaN%')) return color('primaryTextColor');
    throw StateError('Unsupported original diagram palette role: $role');
  }
  core.Color get background => color('background');
  core.Color get surface => color('primaryColor');
  core.Color get foreground => color('primaryTextColor');
  core.Color get border => color('primaryBorderColor');
  String get fontFamily => 'packages/raft_ui/RaftDiagramSans';
  double get fontSize => 16;
}

