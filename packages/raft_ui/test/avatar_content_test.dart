    'uploaded pending stays clean; failed upload falls through to decoded Gravatar',
    (tester) async {
      final upload = _FrameControl(), hash = _FrameControl();
      final providers = {
        uploadedA: _ControlledProvider(upload),
        gravatar: _ControlledProvider(hash),
      };
      final requested = <String>[];
      await tester.pumpWidget(
        frame(
          RaftAvatarContent(
            name: 'Public human',
            uploadedUrl: uploadedA,
            gravatarUrl: gravatar,
            fallback: fallback,
            imageProviderBuilder: (url) {
              requested.add(url);
              return providers[url]!;
            },
          ),
        ),
      );
      expect(requested, [uploadedA]);
      expect(find.byKey(const Key('clean-placeholder')), findsOneWidget);
      upload.reportError(
        exception: StateError('public uploaded fixture failed'),
        stack: StackTrace.current,
      );
      await tester.pump();
      expect(requested, [uploadedA, gravatar]);
      expect(find.byKey(const Key('clean-placeholder')), findsOneWidget);
      hash.deliver(ImageInfo(image: await _image(tester, Colors.blue)));
      await tester.pump();
      expect(find.byKey(const Key('clean-placeholder')), findsNothing);
      expect(tester.widget<RawImage>(find.byType(RawImage)).image!.width, 8);
      await tester.pumpWidget(const SizedBox.shrink());
