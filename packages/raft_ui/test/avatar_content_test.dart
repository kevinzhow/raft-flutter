          RaftAvatarContent(
            name: 'Public human',
            uploadedUrl: 'https://provider.example.test/default.webp',
            gravatarUrl: gravatar,
            fallback: fallback,
            imageProviderBuilder: (url) {
              calls.add(url);
              return _ControlledProvider(control);
