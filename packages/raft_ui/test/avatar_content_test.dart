class _FrameControl extends ImageStreamCompleter {
  void deliver(ImageInfo frame) => setImage(frame);
}

class _ControlledProvider extends ImageProvider<_ControlledProvider> {
  _ControlledProvider(this.control);
  final _FrameControl control;
  @override
  Future<_ControlledProvider> obtainKey(ImageConfiguration configuration) =>
      SynchronousFuture(this);
  @override
  ImageStreamCompleter loadImage(
    _ControlledProvider key,
    ImageDecoderCallback decode,
  ) => control;
}

Future<ui.Image> _image(WidgetTester tester, Color color) async {
  return (await tester.runAsync(() async {
    final recorder = ui.PictureRecorder();
    Canvas(recorder)
        .drawRect(const Rect.fromLTWH(0, 0, 8, 8), Paint()..color = color);
    final picture = recorder.endRecording();
    try {
      return await picture.toImage(8, 8);
    } finally {
      picture.dispose();
    }
  }))!;
}

