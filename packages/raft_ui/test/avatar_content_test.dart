    final providers = {
      uploadedA: _ControlledProvider(a),
      uploadedB: _ControlledProvider(b),
    };
    Widget person(String url) => frame(
      RaftAvatarContent(
        name: 'Public human',
        uploadedUrl: url,
        fallback: fallback,
        imageProviderBuilder: (url) => providers[url]!,
      ),
    );
    await tester.pumpWidget(person(uploadedA));
    await tester.pumpWidget(person(uploadedB));
    a.deliver(ImageInfo(image: await _image(tester, Colors.red)));
    await tester.pump();
    expect(find.byKey(const Key('clean-placeholder')), findsOneWidget);
    expect(find.byType(RawImage), findsNothing);
    b.deliver(ImageInfo(image: await _image(tester, Colors.blue)));
