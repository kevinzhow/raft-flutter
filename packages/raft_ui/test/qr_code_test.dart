void main() {
  for (final (text, size, mask, rows) in _uqr) {
    test('QR matrix matches uqr for $text', () {
      final m = RaftQrMatrix.encode(text);
      expect(m.size, size);
      expect(m.mask, mask);
      final actual = [
        for (var y = 0; y < m.size; y++)
          [for (var x = 0; x < m.size; x++) m.dark(x, y) ? '1' : '0'].join(),
      ].join('|');
      expect(actual, rows);
    });
  }
}
